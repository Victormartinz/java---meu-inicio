public class Main {
    public static void main(String[] args) {

        int pao = 5;
        int cafe = 10;

        System.out.println(pao == cafe);
        System.out.println(pao != cafe);
        System.out.println(pao > cafe);
        System.out.println(pao < cafe);
        System.out.println(pao >= cafe);
        System.out.println(pao <= cafe);
    }
}